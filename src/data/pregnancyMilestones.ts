/**
 * Returns a subset of 36 weeks starting from startWeek (default: 5 up to 40)
 */
export function getMilestoneWeeks(startWeek = 5, totalWeeks = 36): PregnancyWeekInfo[] {
  const filtered = PREGNANCY_WEEKS.filter(
    (w) => w.week >= startWeek && w.week < startWeek + totalWeeks
  );
  if (filtered.length < totalWeeks) {
    return PREGNANCY_WEEKS.slice(0, Math.min(totalWeeks, PREGNANCY_WEEKS.length));
  }
  return filtered;
}
